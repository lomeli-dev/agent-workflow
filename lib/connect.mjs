export const CONNECT_CLIENTS=ALL_CLIENTS.filter(c=>Object.hasOwn(TARGETS,c));
export function parseConnectClients(value){
 if(value===undefined||value===null||value==='')return CLIENTS;
 if(value==='all')return CONNECT_CLIENTS;
 return String(value).split(',').map(c=>c.trim()).filter(Boolean);
}
export function connectionRoot(project){
 const root=projectRoot(project);
 if(realpathSync(project)!==root)throw Error('Project MCP registrations require the repository root; nested paths cannot be silently promoted');
 return root;
}
// Receipts written before 0.6.0 hold one file per client ({client, path, ...}); 0.6.0 receipts
// (schemaVersion 2) hold one entry per file with the clients that read it.
function normalize(old){return old?.schemaVersion===2?old:old&&Array.isArray(old.files)?{...old,files:old.files.map(f=>({...f,clients:[f.client],kind:f.client==='codex'?'toml':'json'}))}:old;}
function validateReceipt(raw,root){
 const old=normalize(raw);
 if(!old||old.project!==root||!Array.isArray(old.clients)||!old.clients.length||new Set(old.clients).size!==old.clients.length||old.clients.some(c=>!CONNECT_CLIENTS.includes(c))||!Array.isArray(old.files))throw Error('Invalid connection receipt');
 if(raw.schemaVersion===undefined&&(old.files.length!==old.clients.length||old.clients.some(c=>!CLIENTS.includes(c))))throw Error('Invalid connection receipt');
 const seenPath=new Set(),covered=new Set();
 for(const f of old.files){
  if(!Array.isArray(f.clients)||!f.clients.length||f.clients.some(c=>!old.clients.includes(c)||covered.has(c)&&TARGETS[c].kind!=='files'))throw Error('Invalid connection receipt');
  const kinds=new Set(f.clients.map(c=>TARGETS[c].kind));
  if(kinds.size!==1||!kinds.has(f.kind)||f.clients.some(c=>!TARGETS[c].paths(root).includes(f.path))||seenPath.has(f.path)||!(f.original===null||typeof f.original==='string')||!(f.afterHash===null||/^[a-f0-9]{64}$/.test(f.afterHash)))throw Error('Invalid connection receipt');
  seenPath.add(f.path);for(const c of f.clients)covered.add(c);
  if(f.originalHash!==undefined&&f.originalHash!==hash(f.original??''))throw Error('Original configuration checksum mismatch');
  if(f.kind==='toml'){if(!/^[a-f0-9]{64}$/.test(f.blockHash))throw Error('Invalid connection block receipt');}
  else if(f.kind==='json'&&(!f.entries||Array.isArray(f.entries)||typeof f.entries!=='object'||Object.keys(f.entries).some(k=>!MCP_TOOLS.some(id=>k==='aw-'+id))))throw Error('Invalid owned MCP entries');
 }
 if(old.clients.some(c=>!covered.has(c)))throw Error('Invalid connection receipt');
 return old;
}
// Project connection receipts, read without modifying anything. `exists` is false when the
// project directory was removed or moved (for example a deleted worktree).
export function connectionReceipts(userRoot){
 const dir=join(locations(userRoot).store,'connections');if(!existsSync(dir))return [];
 return readdirSync(dir).filter(n=>n.endsWith('.json')).sort().map(name=>{
  const path=join(dir,name);let project=null;
  try{project=json(read(path)).project;}catch{}
  return {receipt:path,project:typeof project==='string'?project:null,exists:typeof project==='string'&&existsSync(project)};
 });
}
// Forget receipts whose project no longer exists. There is nothing left to restore there; copies
// of that project's config elsewhere keep their aw-* entries.
export function pruneConnections({userRoot,dryRun=false}={}){
 const orphans=connectionReceipts(userRoot).filter(r=>r.project&&!r.exists);
 const result={pruned:orphans.map(r=>r.project),dryRun,note:'Removed receipts only; nothing inside other checkouts was edited.'};
 if(dryRun||!orphans.length)return result;
 return lock(join(locations(userRoot).store,'connections'),()=>{
  for(const r of orphans){const now=read(r.receipt);if(now===null)continue;if(json(now).project!==r.project||existsSync(r.project))throw Error('Concurrent connection update: '+r.receipt);unlinkSync(r.receipt);}
  return result;
 });
}
export function connectionEntries(project,tools,userRoot){
 const entries={};for(const id of tools){if(!MCP_TOOLS.includes(id))throw Error('Not an MCP module: '+id);entries['aw-'+id]={command:process.execPath,args:[join(PACKAGE,'bin/agent-workflow.mjs'),'mcp','--tool',id,'--project',project,...(userRoot?['--user-root',locations(userRoot).home]:[])]};}return entries;
}

// {} or {"mcp": {"servers": {}}}: nothing but the empty containers of `prefix`. Top-level $ keys are
// metadata the client adds to a file that connect created (Qwen $version, MiMo $schema).
function onlyEmptyChain(value,prefix){
 value=Object.fromEntries(Object.entries(value??{}).filter(([k])=>!k.startsWith('$')));
 for(const key of prefix){const keys=Object.keys(value??{});if(!keys.length)return true;if(keys.length!==1||keys[0]!==key)return false;value=value[key];if(!value||typeof value!=='object'||Array.isArray(value))return false;}
 return Object.keys(value).length===0;
}
// One planned change for a file: JSON/JSONC entries, a TOML managed block, or a whole owned file.
function jsonChange(path,before,previous,prefix,expected,remove){
 let after=before??'',obj=json(after||'{}');
 let container=obj;for(const key of prefix){const next=container?.[key];if(next!==undefined&&(!next||Array.isArray(next)||typeof next!=='object'))throw Error('Invalid MCP container: '+path);container=next;}
 for(const [key,value] of Object.entries(previous?.entries??{})){
  const present=prefix.reduce((v,k)=>v?.[k],obj)?.[key];if(JSON.stringify(present)!==JSON.stringify(value))throw Error('Edited managed MCP entry: '+key);
  after=updateJson(after,prefix.concat(key),undefined);obj=json(after);
 }
 if(!remove)for(const [key,value] of Object.entries(expected)){
  if(prefix.reduce((v,k)=>v?.[k],obj)?.[key]!==undefined)throw Error('MCP name collision: '+key+' in '+path);
  after=updateJson(after,prefix.concat(key),value);
 }
 // An emptied container that Agent Workflow created goes away with the entries.
 if(remove&&previous?.original===null&&onlyEmptyChain(json(after||'{}'),prefix))after=null;
 // Containers that Agent Workflow added (absent in the original) are removed once empty.
 else if(remove&&previous)for(let i=prefix.length;i>0;i--){
  const path=prefix.slice(0,i),now=path.reduce((v,k)=>v?.[k],json(after||'{}')),was=path.reduce((v,k)=>v?.[k],json(previous.original||'{}'));
  if(was===undefined&&now&&typeof now==='object'&&!Array.isArray(now)&&Object.keys(now).length===0)after=updateJson(after,path,undefined);
 }
 return {after,owned:{entries:expected}};
}
function tomlChange(before,previous,entries,remove){
 let after=before??'';const priorBlock=managed(after);parseToml(after);
 if((previous&&!priorBlock)||(priorBlock&&(!previous||hash(priorBlock)!==previous.blockHash)))throw Error('Edited/unowned Codex MCP block');
 const outside=parseToml(replace(after,null));for(const key of Object.keys(entries))if(outside.mcp_servers?.[key])throw Error('MCP name collision: '+key);
 const body=A+'\n'+Object.entries(entries).map(([name,value])=>`[mcp_servers.${JSON.stringify(name)}]\ncommand = ${JSON.stringify(value.command)}\nargs = ${JSON.stringify(value.args)}\n`).join('\n')+B;
 after=replace(after,remove?null:body);parseToml(after);return {after,owned:{blockHash:remove?null:hash(body)}};
}

// Opt-in approval through the client's own mechanism; never a bypass.
//   claude: .claude/settings.local.json enabledMcpjsonServers (the list Claude writes when the user
//           approves .mcp.json servers); only the aw-* names added here are removed again.
//   qwen:   `qwen mcp approve <name>` in the project (Qwen binds the approval to the entry's hash).
const APPROVALS={claude:'enabledMcpjsonServers in .claude/settings.local.json',qwen:'qwen mcp approve <name> (run in the project)'};
function claudeApproval(root,names,previous,remove){
 const path=join(root,'.claude/settings.local.json');noSymlinks(path);const before=read(path);
 let after=before??'{}\n';const list=json(after).enabledMcpjsonServers;
 if(list!==undefined&&!Array.isArray(list))throw Error('enabledMcpjsonServers must be an array: '+path);
 const current=list??[],added=remove?[]:names.filter(n=>!current.includes(n));
 const drop=remove?(previous?.added??[]):[];
 const next=[...current.filter(n=>!drop.includes(n)),...added];
 after=next.length||list!==undefined&&!remove?updateJson(after,['enabledMcpjsonServers'],next):updateJson(after,['enabledMcpjsonServers'],undefined);
 if(remove&&previous?.original===null&&Object.keys(json(after)).length===0)after=null;
 return {path,before,after,added:remove?[]:[...(previous?.added??[]),...added].filter((n,i,a)=>a.indexOf(n)===i),original:previous?previous.original:before};
}
function qwenApprove(root,names,loc,userRoot){
 const env=userRoot?{...process.env,QWEN_HOME:loc.qwen}:process.env,results=[];
 for(const name of names){const r=spawnSync('qwen',['mcp','approve',name],{cwd:root,env,encoding:'utf8',timeout:60000});results.push({name,ok:r.status===0,...(r.status===0?{}:{error:(r.error?.message??r.stderr??'').trim().slice(0,300)})});}
 return results;
}

export function connect({project,tools=DEFAULT_MCP_TOOLS,clients=CLIENTS,userRoot,dryRun=false,remove=false,approve=false}){
 if(!project)throw Error('Specify --project');
 if(!clients.length||new Set(clients).size!==clients.length||clients.some(c=>!CONNECT_CLIENTS.includes(c)))throw Error('Unsupported or duplicate client; use --clients with any of '+CONNECT_CLIENTS.join(',')+' (or all)');
 const root=connectionRoot(project),loc=locations(userRoot),statePath=join(loc.store,'connections',hash(root)+'.json');
 const stateBefore=read(statePath),old=stateBefore?validateReceipt(json(stateBefore),root):null;
 if(remove&&!old)return {removed:false,reason:'not-connected'};
 if(old&&JSON.stringify([...old.clients].sort())!==JSON.stringify([...clients].sort()))throw Error('Connection client set changed; disconnect existing set first');
 const entries=connectionEntries(root,[...new Set(old&&remove?old.tools??tools:tools)],userRoot),changes=[];
 // Group clients by the file they read: .mcp.json is shared by claude, commandcode and kimi.
 const groups=[];
 for(const client of clients){
  const t=TARGETS[client];
  if(t.kind==='files'){
   for(const [path,content] of t.files(root,entries)){const prior=old?.files.find(f=>f.path===path);groups.push({path,clients:[client],kind:'files',content,prior});}
   continue;
  }
  const prior=old?.files.find(f=>f.clients.includes(client)&&f.kind===t.kind);
  const path=prior?.path??(t.select?t.select(root):t.paths(root)[0]);
  if(!remove&&client==='opencode'&&prior&&existsSync(join(root,'opencode.jsonc'))&&prior.path!==join(root,'opencode.jsonc'))throw Error('OpenCode config selection changed; disconnect before reconnecting');
  const same=groups.find(g=>g.path===path);
  if(same){if(same.kind!==t.kind||JSON.stringify(same.prefix)!==JSON.stringify(t.prefix))throw Error('Clients disagree about '+path);same.clients.push(client);continue;}
  groups.push({path,clients:[client],kind:t.kind,prefix:t.prefix,entry:t.entry,prior});
 }
 for(const g of groups){
  noSymlinks(g.path);const before=read(g.path),previous=g.prior;let result;
  if(g.kind==='toml')result=tomlChange(before,previous,entries,remove);
  else if(g.kind==='json')result=jsonChange(g.path,before,previous,g.prefix,Object.fromEntries(Object.entries(entries).map(([k,v])=>[k,g.entry(v)])),remove);
  else{
   if(before!==null&&(!previous||hash(before)!==previous.afterHash))throw Error((previous?'Edited':'Unowned')+' project MCP file: '+g.path);
   result={after:remove?null:g.content,owned:{}};
  }
  let after=result.after;const original=previous?previous.original:before;
  if(remove&&previous&&before!==null&&hash(before)===previous.afterHash&&g.kind!=='files')after=original;
  changes.push({path:g.path,before,after,original,originalHash:hash(original??''),clients:g.clients,kind:g.kind,...result.owned,afterHash:after===null?null:hash(after)});
 }
 const names=Object.keys(entries),oldApproval=old?.approvals?.claude;
 // A recorded approval is kept by later connects (with or without --approve) until disconnect.
 const approvalChange=clients.includes('claude')&&(approve||oldApproval)?claudeApproval(root,names,oldApproval,remove):null;
 if(approvalChange&&approvalChange.before!==approvalChange.after)changes.push({path:approvalChange.path,before:approvalChange.before,after:approvalChange.after,approval:true});
 if(dryRun)return {dryRun:true,project:root,remove,files:changes.map(f=>f.path),tools:Object.keys(entries).map(n=>n.slice(3)),...(approve?{approve:Object.fromEntries(clients.filter(c=>APPROVALS[c]).map(c=>[c,APPROVALS[c]]))}:{})};
 return lock(join(loc.store,'connections'),()=>{
  if(read(statePath)!==stateBefore)throw Error('Concurrent connection update');
  const completed=[];try{
   for(const f of changes){if(read(f.path)!==f.before)throw Error('Concurrent config edit');if(f.after===null){if(f.before!==null)unlinkSync(f.path);}else atomic(f.path,f.after);completed.push(f);}
   const approvals=approvalChange&&!remove?{claude:{added:approvalChange.added,original:approvalChange.original}}:undefined;
   if(remove)unlinkSync(statePath);else atomic(statePath,JSON.stringify({schemaVersion:2,project:root,clients,tools:Object.keys(entries).map(n=>n.slice(3)),files:changes.filter(f=>!f.approval).map(({before,after,approval,...f})=>f),...(approvals?{approvals}:{})},null,2)+'\n');
  }catch(e){for(const f of completed.reverse())if(read(f.path)===f.after){if(f.before===null)unlinkSync(f.path);else atomic(f.path,f.before);}throw e;}
  const qwen=!remove&&approve&&clients.includes('qwen')?qwenApprove(root,names,loc,userRoot):undefined;
  const pending=clients.filter(c=>NEEDS_APPROVAL[c]&&!(approve&&APPROVALS[c]));
  return {project:root,connected:!remove,files:changes.map(f=>f.path),tools:Object.keys(entries).map(n=>n.slice(3)),...(qwen?{qwenApproval:qwen}:{}),...(!remove&&pending.length?{approval:Object.fromEntries(pending.map(c=>[c,NEEDS_APPROVAL[c]]))}:{}),note:'Registrations only; restart/reload each client. No credentials copied. Keep these files out of commits with .git/info/exclude if they are local.'};
 });
}
